-- Admin Cộng đồng — Danh mục bài viết (taxonomy)
CREATE TABLE IF NOT EXISTS community_categories (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(160) NOT NULL,
    slug VARCHAR(160) NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    icon VARCHAR(64) NOT NULL DEFAULT 'ti ti-folder',
    color VARCHAR(32) NOT NULL DEFAULT '#696CFF',
    cover_url TEXT,
    parent_id UUID REFERENCES community_categories(id) ON DELETE SET NULL,
    sort_order INT NOT NULL DEFAULT 0,
    is_visible BOOLEAN NOT NULL DEFAULT TRUE,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    post_count INT NOT NULL DEFAULT 0,
    seo_title VARCHAR(255) NOT NULL DEFAULT '',
    seo_description TEXT NOT NULL DEFAULT '',
    seo_keywords TEXT NOT NULL DEFAULT '',
    created_by_name VARCHAR(120) NOT NULL DEFAULT 'Hệ thống',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_com_cat_parent ON community_categories(parent_id);
CREATE INDEX IF NOT EXISTS idx_com_cat_sort ON community_categories(sort_order, name);
CREATE INDEX IF NOT EXISTS idx_com_cat_visible ON community_categories(is_visible, is_featured);

